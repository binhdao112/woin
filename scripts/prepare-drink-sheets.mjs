import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

export async function buildDrinkSheetsBundle() {
  const root = new URL('../',import.meta.url);
  const [core,menu,handler] = await Promise.all(['dist/drink-orders.js','dist/assets/drinks/koi-menu.json','integrations/google-sheets/handler.gs'].map(file=>readFile(new URL(file,root),'utf8')));
  return '// Generated by npm run prepare:drinks. Paste this entire file into Apps Script.\n' + 'const KOI_MENU = ' + JSON.stringify(JSON.parse(menu)) + ';\n' + core.replace(/^export /gm,'') + '\n' + handler;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = new URL('../integrations/google-sheets/Code.gs',import.meta.url), bundle = await buildDrinkSheetsBundle();
  if (process.argv.includes('--check')) {
    if (await readFile(target,'utf8') !== bundle) throw Error('Apps Script chưa đồng bộ với menu/logic. Chạy npm run prepare:drinks.');
    console.log('Apps Script bundle matches menu and validation.');
  } else { await mkdir(new URL('.',target),{recursive:true}); await writeFile(target,bundle);console.log('Đã tạo integrations/google-sheets/Code.gs'); }
}
